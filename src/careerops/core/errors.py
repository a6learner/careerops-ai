from enum import StrEnum

from pydantic import BaseModel, Field


class ErrorCode(StrEnum):
    PROJECT_RECORD_NOT_FOUND = "PROJECT_RECORD_NOT_FOUND"
    PROJECT_RECORD_CONFLICT = "PROJECT_RECORD_CONFLICT"
    ACTION_ITEM_NOT_FOUND = "ACTION_ITEM_NOT_FOUND"
    ACTION_ITEM_SOURCE_NOT_ACTIONABLE = "ACTION_ITEM_SOURCE_NOT_ACTIONABLE"
    ACTION_ITEM_SOURCE_NOT_FOUND = "ACTION_ITEM_SOURCE_NOT_FOUND"
    ACTION_ITEM_VERSION_CONFLICT = "ACTION_ITEM_VERSION_CONFLICT"
    ANALYSIS_RUN_NOT_FOUND = "ANALYSIS_RUN_NOT_FOUND"
    ANALYSIS_RATE_LIMITED = "ANALYSIS_RATE_LIMITED"
    ASSISTED_RESOURCE_CONFLICT = "ASSISTED_RESOURCE_CONFLICT"
    ASSISTED_RESOURCE_NOT_FOUND = "ASSISTED_RESOURCE_NOT_FOUND"
    DEPENDENCY_UNAVAILABLE = "DEPENDENCY_UNAVAILABLE"
    EMAIL_ALREADY_REGISTERED = "EMAIL_ALREADY_REGISTERED"
    EXPERIENCE_NOT_FOUND = "EXPERIENCE_NOT_FOUND"
    EXPERIENCE_VERSION_CONFLICT = "EXPERIENCE_VERSION_CONFLICT"
    IF_MATCH_REQUIRED = "IF_MATCH_REQUIRED"
    IDEMPOTENCY_KEY_CONFLICT = "IDEMPOTENCY_KEY_CONFLICT"
    IDEMPOTENCY_KEY_REQUIRED = "IDEMPOTENCY_KEY_REQUIRED"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    INVALID_CURSOR = "INVALID_CURSOR"
    INVALID_CREDENTIALS = "INVALID_CREDENTIALS"
    INVALID_DOCUMENT = "INVALID_DOCUMENT"
    JOB_NOT_FOUND = "JOB_NOT_FOUND"
    JOB_VERSION_CONFLICT = "JOB_VERSION_CONFLICT"
    NO_ACTIVE_EXPERIENCES = "NO_ACTIVE_EXPERIENCES"
    PARSE_RUN_NOT_FOUND = "PARSE_RUN_NOT_FOUND"
    PARSE_RUN_NOT_READY = "PARSE_RUN_NOT_READY"
    TOKEN_EXPIRED = "TOKEN_EXPIRED"
    TOKEN_INVALID = "TOKEN_INVALID"
    TOKEN_MISSING = "TOKEN_MISSING"
    VALIDATION_ERROR = "VALIDATION_ERROR"


class ErrorDetail(BaseModel):
    code: ErrorCode
    message: str
    details: dict[str, object] = Field(default_factory=dict)
    request_id: str


class ErrorResponse(BaseModel):
    error: ErrorDetail
